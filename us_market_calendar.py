"""미국 증시(NYSE·나스닥) 조기 폐장일 — 그날은 오후 1시(뉴욕 시간)에 닫힌다. 2026-11-26 인선.

평소 미국 주문은 '오늘 마감(16:00 뉴욕) 앞뒤 20분'에만 돈다. 조기 폐장일에도 16:00 으로 계산하면 장이 닫힌 뒤
(한국 시간 새벽 4~6시)에 주문하게 돼서, 공포 매수 조건이 와도 정규장 안에 못 들어간다 → 그날은 13:00 으로.
해마다 NYSE 공지(https://www.nyse.com/markets/hours-calendars)를 보고 다음 해 날짜를 더한다.
휴장일(추수감사절·성탄절 등)은 따로 막지 않는다 — 그날은 증권사 주문이 거절되거나 시세가 전날 그대로라 매매가 일어나지 않는다.
"""
from datetime import date

EARLY_CLOSE = {
    date(2026, 11, 27): "추수감사절 다음 날",
    date(2026, 12, 24): "성탄절 전날",
    date(2027, 11, 26): "추수감사절 다음 날",
}


def nyse_close_hour(d: date) -> int:
    """그날 뉴욕 시간 마감 시각(시). 평소 16, 조기 폐장일 13."""
    return 13 if d in EARLY_CLOSE else 16
